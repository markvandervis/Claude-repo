import math
import os
import random
import re
import struct
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
import mcfilm_model as m          # noqa: E402
import build_dctl                 # noqa: E402

DCTL = build_dctl.OUTPUT
HARNESS = os.path.join(HERE, "mcf_harness")
TABLES = m.prepare(m.load_tables(build_dctl.TABLES_JSON))

_fail, _n = [], 0


def check(ok, msg):
    global _n
    _n += 1
    print(("  ok    " if ok else "  FAIL  ") + msg)
    if not ok:
        _fail.append(msg)


def section(t):
    print("\n=== %s ===" % t)


def f32(v):
    return struct.unpack("<f", struct.pack("<f", v))[0]


def build():
    lines = ["// generated by test_film_core.py from tools/mcfilm_model.py"]
    for lst in (m.INPUTS, m.NEGATIVES, m.PRINTS, m.OUTPUTS):
        lines.append("enum { %s };" % ", ".join("%s = %d" % (e[0], i) for i, e in enumerate(lst)))
    lines.append("enum { BB_OFF = 0, BB_AUTHENTIC = 1, BB_GRUNGE = 2 };")
    lines.append("enum { BS_PRINT = 0, BS_NEGATIVE = 1 };")
    open(os.path.join(HERE, "mcf_enums.h"), "w").write("\n".join(lines) + "\n")
    define = '-DMCF_DCTL="../%s"' % os.path.basename(DCTL)
    flags = ["-O2", "-Wall", "-Wextra", "-Wno-unused-parameter", "-Werror", define]
    for cmd in (["g++", "-std=c++11"] + flags + ["-o", HARNESS, "mcf_harness.cpp"],
                ["gcc", "-std=c99"] + flags + ["-c", "-o", "/dev/null", "mcf_c_check.c"]):
        r = subprocess.run(cmd, cwd=HERE, capture_output=True, text=True)
        if r.returncode:
            print(r.stderr[:4000])
            sys.exit("build failed")
    print("built tests/mcf_harness; DCTL compiles clean as C++11 and C99")


def run(pixels, **ui):
    args = ["%s=%s" % (k, v) for k, v in ui.items()]
    payload = "".join("%s %s %s\n" % tuple(float(c).hex() for c in p) for p in pixels)
    r = subprocess.run([HARNESS] + args, input=payload, capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError(r.stderr)
    return [tuple(float.fromhex(x) for x in l.split()) for l in r.stdout.splitlines()]


ENC = {e: i for i, (e, _) in enumerate(m.INPUTS)}
OUT = {e: i for i, (e, _) in enumerate(m.OUTPUTS)}


def di_encode(x):
    return (math.log2(x + 0.0075) + 7.0) * 0.07329248 if x > 0.00262409 else x * 10.44426855


def hsv(h, s, v):
    h %= 360.0
    c = v * s
    x = c * (1 - abs(math.fmod(h / 60.0, 2) - 1))
    r, g, b = [(c, x, 0), (x, c, 0), (0, c, x), (0, x, c), (x, 0, c), (c, 0, x)][int(h // 60) % 6]
    return (r + v - c, g + v - c, b + v - c)


