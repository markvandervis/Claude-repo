def test_static():
    section("1. static checks")
    src = open(DCTL, encoding="utf-8").read()
    lines = src.split("\n")
    banner = ["// MarkCaptures MC Film Core", "// © 2026 Mark van der Vis / MarkCaptures",
              "// www.markcaptures.com"]
    check(lines[:3] == banner and [l for l in lines if l.strip()][-3:] == banner, "banner at top and bottom")
    entry = [l for l in lines if "float3 transform(" in l]
    check(len(entry) == 1 and entry[0] == "__DEVICE__ float3 transform(int p_Width, int p_Height, "
          "int p_X, int p_Y, float p_R, float p_G, float p_B)", "transform() on one line")
    params = re.findall(r"^DEFINE_UI_PARAMS\((\w+),", src, re.M)
    tips = set(re.findall(r"^DEFINE_UI_TOOLTIP\((\w+),", src, re.M))
    check(set(params) == tips, "every control has a tooltip")
    code = re.sub(r"//.*", "", src)
    check("_exp10f" not in code, "no _exp10f")
    intr = set(re.findall(r"\b(_[a-z][a-z0-9]*)\s*\(", code))
    check(intr <= {"_fmaxf", "_fminf", "_fabs", "_powf", "_exp2f", "_log2f", "_floor"},
          "only standard intrinsics (%s)" % sorted(intr))
    check("CC BY-SA 4.0" in src and "Andrea Volpato" in src and "github.com/andreavolpato/spektrafilm" in src,
          "stock data attribution present")
    check(not re.search(r"\bdouble\b", code), "no double precision")
    n_floats = sum(int(x) for x in re.findall(r"__CONSTANT__ float \w+\[(\d+)\]", src))
    check(n_floats * 4 < 60 * 1024, "constant tables fit GPU constant memory (%d KB)" % (n_floats * 4 // 1024))


def test_cross():
    section("2. DCTL == Python reference")
    rng = random.Random(1)
    px = [(rng.uniform(0, 0.7), rng.uniform(0, 0.7), rng.uniform(0, 0.7)) for _ in range(40)]
    px += [(di_encode(v),) * 3 for v in (0.0, 0.002, 0.02, 0.18, 1.0, 8.0)]
    px = [tuple(f32(c) for c in p) for p in px]
    worst = 0.0
    for ni in range(len(m.NEGATIVES)):
        for pi in range(len(m.PRINTS)):
            for oi, (oe, _) in enumerate(m.OUTPUTS):
                if oe != "OUT_709" and (ni + pi) % 3:
                    continue
                bleach = rng.choice(["off", "authentic", "grunge"])
                stage = rng.choice(["print", "negative"])
                ui = dict(uiNegative=ni, uiPrint=pi, uiOutput=oi, uiExposure=rng.uniform(-2, 2),
                          uiPushPull=rng.uniform(-1, 2), uiPrinterRed=rng.uniform(-10, 10),
                          uiPrinterBlue=rng.uniform(-10, 10), uiPrintContrast=rng.uniform(0.8, 1.2),
                          uiFilmSat=rng.uniform(0, 2), uiBleach=["off", "authentic", "grunge"].index(bleach),
                          uiBleachStage=["print", "negative"].index(stage),
                          uiBleachStrength=rng.uniform(0, 1), uiSilverContrast=rng.uniform(0.5, 2),
                          uiPreserveMid=rng.choice([0, 1]))
                a = run(px, **ui)
                b = [m.render_pixel(np.array(p), TABLES, ni, pi, "IN_DWG", oe, ui["uiExposure"],
                                    ui["uiPushPull"], (ui["uiPrinterRed"], 0.0, ui["uiPrinterBlue"]), 0.0,
                                    1.0, ui["uiPrintContrast"], True, ui["uiFilmSat"], bleach, stage,
                                    ui["uiBleachStrength"], ui["uiSilverContrast"], bool(ui["uiPreserveMid"]))
                     for p in px]
                worst = max(worst, max(abs(x - y) for pa, pb in zip(a, b) for x, y in zip(pa, pb)))
    check(worst < 2e-4, "max |DCTL - reference| over all stocks and outputs = %.1e" % worst)


def test_neutral():
    section("3. 18 % grey prints neutral")
    grey = [(f32(di_encode(m.MIDGRAY)),) * 3]
    worst, lvl = 0.0, []
    for ni in range(len(m.NEGATIVES)):
        for pi in range(len(m.PRINTS)):
            o = run(grey, uiNegative=ni, uiPrint=pi)[0]
            worst = max(worst, max(o) - min(o))
            lvl.append(o[1])
    check(worst < 2e-3, "18 %% grey neutral within %.1e for all %d combinations" % (worst, len(lvl)))
    print("        printed 18 %% grey: %.3f .. %.3f (Rec709 gamma 2.4 code value)" % (min(lvl), max(lvl)))


def test_ramps():
    section("4. grey ramps: monotonic and smooth over 16 stops")
    stops = np.linspace(-10, 6, 801)
    px = [(f32(di_encode(m.MIDGRAY * 2 ** s)),) * 3 for s in stops]
    worst_back, worst_jump = 0.0, 0.0
    for ni in range(len(m.NEGATIVES)):
        for pi in range(len(m.PRINTS)):
            for ui in ({}, dict(uiPushPull=2.5), dict(uiPushPull=-2.0, uiNegContrast=0.5),
                       dict(uiPrintContrast=1.5, uiExposure=3.0),
                       dict(uiBleach=2, uiBleachStrength=1.0, uiSilverContrast=2.0),
                       dict(uiBleach=2, uiBleachStage=1, uiBleachStrength=1.0, uiSilverContrast=2.0),
                       dict(uiBleach=1, uiBleachStage=1, uiPreserveMid=0, uiFilmSat=2.0)):
                out = run(px, uiNegative=ni, uiPrint=pi, **ui)
                y = np.array([0.2126 * o[0] + 0.7152 * o[1] + 0.0722 * o[2] for o in out])
                d = np.diff(y)
                worst_back = max(worst_back, -d.min())
                worst_jump = max(worst_jump, d.max())
    check(worst_back < 1e-5, "grey ramp never gets darker as exposure rises (worst %.1e)" % worst_back)
    check(worst_jump < 0.02, "no jumps along the ramp (largest step %.4f per 1/50 stop)" % worst_jump)


def test_hue():
    section("5. hue sweeps: continuous, finite")
    hues = np.arange(0, 360, 0.25)
    worst = 0.0
    bad = False
    for ni in (0, 1, 3, 6, 10):
        for pi in (0, 2, 7):
            for s in (0.3, 0.8, 1.0):
                px = [tuple(f32(di_encode(v)) for v in hsv(h, s, 0.5)) for h in hues]
                out = np.array(run(px, uiNegative=ni, uiPrint=pi))
                bad |= not np.all(np.isfinite(out))
                # judged in linear light: the display gamma x^(1/2.4) has an
                # infinite slope at 0, so a channel crossing zero (a print
                # colour just outside Rec.709) would look like a jump in code
                # values without being one
                worst = max(worst, np.abs(np.diff(out ** 2.4, axis=0)).max())
    check(not bad, "no NaN / Inf in hue sweeps")
    check(worst < 0.01, "no jumps in hue sweeps (largest linear step %.4f per 0.25 deg)" % worst)


def test_controls():
    section("6. controls")
    g = [(f32(di_encode(m.MIDGRAY)),) * 3]
    base = run(g)[0]
    up = run(g, uiExposure=1.0)[0]
    check(up[1] > base[1] + 0.02, "Exposure +1 brightens the print (%.3f -> %.3f)" % (base[1], up[1]))
    pe = run(g, uiPrintExposure=10)[0]
    check(pe[1] < base[1] - 0.02, "Print Exposure +10 points darkens the print (%.3f)" % pe[1])
    r = run(g, uiPrinterRed=10)[0]
    check(r[0] < r[1] and r[0] < r[2], "Printer Red +10 makes the print less red %s" % str(np.round(r, 3)))
    gr = run(g, uiPrinterGreen=10)[0]
    check(gr[1] < gr[0] and gr[1] < gr[2], "Printer Green +10 makes the print less green")
    b = run(g, uiPrinterBlue=10)[0]
    check(b[2] < b[0] and b[2] < b[1], "Printer Blue +10 makes the print warmer")

    ramp = [(f32(di_encode(m.MIDGRAY * 2 ** s)),) * 3 for s in (-1.0, 1.0)]

    def contrast(**ui):
        o = run(ramp, **ui)
        return o[1][1] - o[0][1]
    c0 = contrast()
    check(contrast(uiPushPull=2.0) > c0 * 1.05, "Push +2 raises contrast")
    check(contrast(uiPushPull=-1.5) < c0 * 0.97, "Pull -1.5 lowers contrast")
    check(contrast(uiPrintContrast=1.3) > c0 * 1.1, "Print Contrast 1.3 raises contrast")

    cin = run([(f32(di_encode(v)),) * 3 for v in (0.0, m.MIDGRAY, 4.0)], uiOutput=OUT["OUT_CINEON"])
    check(abs(cin[0][1] - 95 / 1023) < 0.01 and cin[0][1] < cin[1][1] < cin[2][1] < 1.0,
          "Cineon output: black at code 95, rising with exposure (%.3f %.3f %.3f)" %
          (cin[0][1], cin[1][1], cin[2][1]))
    px = [(0.1, 0.5, 0.9), (-1.0, 2.0, 0.5)]
    check(run(px, uiBypass=1) == [tuple(f32(c) for c in p) for p in px], "Bypass is bit exact")

    # input encodings agree on the same scene colour
    lin = (0.3, 0.12, 0.05)
    dwg_lin = np.linalg.solve(m.DWG_TO_REC709, np.array(lin))
    outs = [run([tuple(f32(di_encode(v)) for v in dwg_lin)], uiInput=ENC["IN_DWG"])[0],
            run([tuple(f32(v) for v in lin)], uiInput=ENC["IN_LINEAR"])[0],
            run([tuple(f32(v ** (1 / 2.4)) for v in lin)], uiInput=ENC["IN_709"])[0]]
    spread = max(abs(a - b) for o in outs[1:] for a, b in zip(o, outs[0]))
    check(spread < 2e-3, "DWG, Scene Linear and Rec709 inputs agree on the same colour (%.1e)" % spread)


def chroma(o):
    return max(o) - min(o)


def test_film_sat_bleach():
    section("6b. Film Saturation and Bleach Bypass")
    g = [(f32(di_encode(m.MIDGRAY)),) * 3]
    col = [tuple(f32(di_encode(v)) for v in (0.30, 0.12, 0.06)), tuple(f32(di_encode(v)) for v in (0.05, 0.10, 0.30))]
    base = run(col)
    bw = run(col, uiFilmSat=0.0)
    # a grey of another exposure is not exactly neutral on every print (2383
    # rolls off warm), so "grey" means: almost all of the chroma is gone
    check(all(chroma(a) < 0.1 * chroma(b) for a, b in zip(bw, base)),
          "Film Saturation 0 renders colours as the film's greys (chroma %.3f, %.3f)" % tuple(chroma(o) for o in bw))
    hi = run(col, uiFilmSat=1.5)
    check(all(chroma(h) > chroma(b) * 1.08 for h, b in zip(hi, base)), "Film Saturation 1.5 raises saturation")
    for v in (0.0, 0.5, 1.5, 2.0):
        o = run(g, uiFilmSat=v)[0]
        if v == 0.0:
            ref0 = o
    check(all(abs(a - b) < 1e-5 for v in (0.5, 1.5, 2.0) for a, b in zip(run(g, uiFilmSat=v)[0], ref0)),
          "Film Saturation leaves 18 % grey unchanged")

    g0 = run(g)[0]
    ramp2 = [(f32(di_encode(m.MIDGRAY * 2 ** s)),) * 3 for s in (-1.0, 1.0)]

    def contrast(**ui):
        o = run(ramp2, **ui)
        return o[1][1] - o[0][1]
    for stage, name in ((0, "print"), (1, "negative")):
        for mode, mname in ((1, "Authentic"), (2, "Grunge")):
            o = run(col, uiBleach=mode, uiBleachStage=stage, uiBleachStrength=1.0)
            if stage == 0:
                check(all(chroma(a) < chroma(b) * 0.9 for a, b in zip(o, base)),
                      "Bleach %s at the print desaturates colours" % mname)
            check(contrast(uiBleach=mode, uiBleachStage=stage, uiBleachStrength=1.0) > contrast() * 1.03,
                  "Bleach %s at the %s raises contrast" % (mname, name))
            gm = run(g, uiBleach=mode, uiBleachStage=stage, uiBleachStrength=1.0)[0]
            tol = 1e-4 if stage == 1 else 0.025      # print stage: first-order re-timing, < 1/10 stop
            check(abs(gm[1] - g0[1]) < tol, "Bleach %s at the %s keeps 18 %% grey (%.4f vs %.4f)" %
                  (mname, name, gm[1], g0[1]))
            gr = run(g, uiBleach=mode, uiBleachStage=stage, uiBleachStrength=1.0, uiPreserveMid=0)[0]
            if stage == 0:
                check(gr[1] < g0[1] - 0.01, "Bleach %s at the print without re-timing darkens the print" % mname)
            else:
                check(gr[1] > g0[1] + 0.01,
                      "Bleach %s at the negative without re-timing lightens the print (denser negative)" % mname)
    deep = [(f32(di_encode(m.MIDGRAY * 2 ** -5)),) * 3]
    check(run(deep, uiBleach=2, uiBleachStrength=1.0)[0][1] < run(deep)[0][1],
          "Grunge on the print deepens the blacks")
    off = run(col, uiBleach=0, uiBleachStrength=1.0, uiSilverContrast=2.0)
    check(off == base, "Bleach Off ignores Bleach Strength and Silver Contrast (bit exact)")


def test_extremes():
    section("7. extreme inputs")
    px = [(0, 0, 0), (1e6, 1e6, 1e6), (-5, -5, -5), (50, -3, 0.2), (1e-30, 0, 0), (0.5, 0.5, -20)]
    ok = True
    for ni in range(len(m.NEGATIVES)):
        for pi in range(len(m.PRINTS)):
            for oi in range(len(m.OUTPUTS)):
                for inp in range(len(m.INPUTS)):
                    out = run(px, uiNegative=ni, uiPrint=pi, uiOutput=oi, uiInput=inp,
                              uiExposure=4, uiPushPull=2.5, uiFilmSat=2.0, uiBleach=2,
                              uiBleachStage=(ni + oi) % 2, uiBleachStrength=1.0, uiSilverContrast=2.0)
                    ok &= all(math.isfinite(v) for o in out for v in o)
    check(ok, "finite output for extreme inputs, every stock / output / input")


def main():
    build()
    test_static()
    test_cross()
    test_neutral()
    test_ramps()
    test_hue()
    test_controls()
    test_film_sat_bleach()
    test_extremes()
    print("\n%d checks, %d failed" % (_n, len(_fail)))
    return 1 if _fail else 0


if __name__ == "__main__":
    sys.exit(main())
