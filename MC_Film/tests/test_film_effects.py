"""Test suite for MC Film Grain and MC Film Halation.

MarkCaptures MC Film - (c) 2026 Mark van der Vis / MarkCaptures.
All rights reserved; see ../LICENSE.txt.

Compiles both generated DCTLs on the host (C++11 and C99, warnings as errors)
and checks them against tools/mcfilm_effects.py and against what they claim:

  grain     - off is bit exact; DCTL == reference; measured RMS matches the
              calibrated granularity; zero mean; no grid pattern (variance is
              the same at every position inside a grain cell); bigger grain on
              smaller gauges; Grain Colour 0 / 1 = shared / independent layers;
              seeds; sub-pixel grain follows Selwyn's law; finite output;
              the full chain Core -> Grain -> Core.
  halation  - off is bit exact; DCTL == reference; an even field is untouched;
              red light is redistributed, not added; the halo is red-orange,
              blue untouched; halo size follows the gauge; the threshold.

Run:  python3 tests/test_film_effects.py      (run tests/test_film_core.py once first)
"""

import math
import os
import random
import struct
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
import mcfilm_model as m          # noqa: E402
import mcfilm_effects as fx       # noqa: E402
import build_dctl                 # noqa: E402

_fail, _n = [], 0


def check(ok, msg):
    global _n
    _n += 1
    print(("  ok    " if ok else "  FAIL  ") + msg)
    if not ok:
        _fail.append(msg)


def section(t):
    print("\n=== %s ===" % t)


def f32(v):
    return struct.unpack("<f", struct.pack("<f", v))[0]


def write_enums():
    lines = ["// generated by the test suites"]
    for lst in (m.INPUTS, m.NEGATIVES, m.PRINTS, m.OUTPUTS, m.WHITES, fx.GAUGES):
        lines.append("enum { %s };" % ", ".join("%s = %d" % (e[0], i) for i, e in enumerate(lst)))
    lines += ["enum { BB_OFF = 0, BB_AUTHENTIC = 1, BB_GRUNGE = 2 };", "enum { BS_PRINT = 0, BS_NEGATIVE = 1 };",
              "enum { HE_DWG = 0, HE_ACESCCT = 1, HE_LINEAR = 2 };", "enum { HQ_DRAFT = 0, HQ_GOOD = 1, HQ_BEST = 2, HQ_ULTRA = 3 };", "enum { HS_MATCHED = 0, HS_PHYSICAL = 1 };"]
    open(os.path.join(HERE, "mcf_enums.h"), "w").write("\n".join(lines) + "\n")


def build():
    write_enums()
    flags = ["-O2", "-Wall", "-Wextra", "-Wno-unused-parameter", "-Werror"]
    for key, path in (("GRAIN", build_dctl.GRAIN_OUTPUT), ("HALATION", build_dctl.HALO_OUTPUT)):
        define = '-DMCF_DCTL="../%s"' % os.path.basename(path)
        exe = os.path.join(HERE, "fx_" + key.lower())
        for cmd, inp in ((["g++", "-std=c++11"] + flags + ["-DMCF_" + key, define, "-o", exe, "fx_harness.cpp"], None),
                         (["gcc", "-std=c99"] + flags + [define, "-x", "c", "-c", "-o", "/dev/null", "-"],
                          '#include "mcf_shim.h"\n#include MCF_DCTL\n')):
            r = subprocess.run(cmd, cwd=HERE, input=inp, capture_output=True, text=True)
            if r.returncode:
                print(r.stderr[:3000])
                sys.exit("build failed")
    print("built tests/fx_grain and tests/fx_halation; both DCTLs compile clean as C++11 and C99")


def run(exe, frame, w, h, **ui):
    payload = "%d %d\n" % (w, h) + "".join("%s %s %s\n" % tuple(float(c).hex() for c in p) for p in frame)
    r = subprocess.run([os.path.join(HERE, exe)] + ["%s=%s" % kv for kv in ui.items()],
                       input=payload, capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError(r.stderr)
    return np.array([[float.fromhex(x) for x in l.split()] for l in r.stdout.splitlines()]).reshape(h, w, 3)


def cineon(d):
    return f32(fx.CINEON_BLACK + d / fx.CINEON_DPC)


def to_density(c):
    return (c - fx.CINEON_BLACK) * fx.CINEON_DPC


NEG250 = [k for _, _, k in m.NEGATIVES].index("kodak_vision3_250d")
G8, S8, G16, S16, S35, G65 = range(6)


# ---------------------------------------------------------------------------
def test_grain():
    section("grain")
    rng = random.Random(3)
    w, h = 40, 24
    frame = [(cineon(rng.uniform(0, 2)), cineon(rng.uniform(0, 2)), cineon(rng.uniform(0, 2))) for _ in range(w * h)]
    out = run("fx_grain", frame, w, h, uiGrainAmount=0)
    check(np.array_equal(out.reshape(-1, 3), np.array(frame)), "Grain Amount 0 is bit exact")
    out = run("fx_grain", frame, w, h, uiBypass=1)
    check(np.array_equal(out.reshape(-1, 3), np.array(frame)), "Bypass is bit exact")

    # DCTL == reference, on a frame wide enough for real multi-pixel grain
    for gauge, width in ((S8, 40), (S16, 40)):
        ui = dict(uiGauge=gauge, uiNegative=NEG250, uiGrainAmount=1.3, uiGrainSize=1.4, uiSeed=7)
        a = run("fx_grain", frame, width, h, **ui)
        worst = 0.0
        for y in range(h):
            for x in range(width):
                b = fx.grain_pixel(frame[y * width + x], x, y, width, "kodak_vision3_250d", gauge,
                                   1.3, 1.4, 0.8, 1.0, 7)
                worst = max(worst, max(abs(p - q) for p, q in zip(a[y, x], b)))
        check(worst < 2e-5, "DCTL == reference (%s, max diff %.1e)" % (fx.GAUGES[gauge][1], worst))

    # statistics on an even D = 1.0 field, 1024 px wide
    W, H = 1024, 96
    flat = [(cineon(1.0),) * 3] * (W * H)
    g = fx.GRANULARITY_X1000["kodak_vision3_250d"] / 1000.0

    def grain_of(**ui):
        o = run("fx_grain", flat, W, H, uiNegative=NEG250, **ui)
        return to_density(o) - 1.0

    for gauge in (S8, G16):
        foot = fx.GAUGES[gauge][2] * 1000.0 / W
        cell_px = fx.GRAIN_CELL_UM / foot
        target = g * fx.APERTURE_UM / fx.GRAIN_CELL_UM
        n = grain_of(uiGauge=gauge, uiGrainColour=1.0)
        sd = n[..., 1].std()
        check(abs(sd / target - 1.0) < 0.06, "%s: measured grain RMS %.4f vs calibrated %.4f (cell %.2f px)" %
              (fx.GAUGES[gauge][1], sd, target, cell_px))
        check(abs(n[..., 1].mean()) < 0.05 * target, "%s: grain has zero mean (%.1e)" % (fx.GAUGES[gauge][1], n[..., 1].mean()))
        # stationarity: variance against the position inside the (layer) cell
        c = cell_px * fx.LAYER_SIZE[1]
        phase = ((np.arange(W) + 0.5) / c) % 1.0
        bins = [n[:, (phase >= b / 6) & (phase < (b + 1) / 6), 1].var() for b in range(6)]
        spread = (max(bins) - min(bins)) / np.mean(bins)
        check(spread < 0.15, "%s: no grid pattern (variance across cell positions within %.0f %%)" %
              (fx.GAUGES[gauge][1], 100 * spread))

    def lag1(n):
        a = n[:, :-1, 1].ravel()
        b = n[:, 1:, 1].ravel()
        return float(np.corrcoef(a, b)[0, 1])
    c8, c16 = lag1(grain_of(uiGauge=S8)), lag1(grain_of(uiGauge=G16))
    check(c8 > c16 + 0.1, "Super 8 grain is coarser than 16mm grain (1-px correlation %.2f vs %.2f)" % (c8, c16))

    n = grain_of(uiGauge=S8, uiGrainColour=0.0)
    check(np.corrcoef(n[..., 0].ravel(), n[..., 2].ravel())[0, 1] > 0.9,
          "Grain Colour 0: the dye layers share one grain pattern")
    n = grain_of(uiGauge=S8, uiGrainColour=1.0)
    check(abs(np.corrcoef(n[..., 0].ravel(), n[..., 2].ravel())[0, 1]) < 0.05,
          "Grain Colour 1: the dye layers' grain is independent")
    a, b = grain_of(uiGauge=S8, uiSeed=1), grain_of(uiGauge=S8, uiSeed=2)
    check(abs(np.corrcoef(a[..., 1].ravel(), b[..., 1].ravel())[0, 1]) < 0.05, "different seeds give unrelated grain")
    check(np.array_equal(a, grain_of(uiGauge=S8, uiSeed=1)), "the same seed gives the same grain")

    # sub-pixel grain (Super 35 at 1024 px: cell < 1 px) follows Selwyn's law
    foot = fx.GAUGES[S35][2] * 1000.0 / W
    target = g * fx.APERTURE_UM / fx.GRAIN_CELL_UM * (fx.GRAIN_CELL_UM / foot)
    sd = grain_of(uiGauge=S35, uiGrainColour=1.0)[..., 1].std()
    check(abs(sd / target - 1.0) < 0.06, "sub-pixel grain RMS scales with Selwyn's law (%.4f vs %.4f)" % (sd, target))

    # density law: denser negative, more grain
    lo = run("fx_grain", [(cineon(0.3),) * 3] * (W * 32), W, 32, uiNegative=NEG250, uiGauge=S8)
    hi = run("fx_grain", [(cineon(1.6),) * 3] * (W * 32), W, 32, uiNegative=NEG250, uiGauge=S8)
    r = (to_density(hi)[..., 1] - 1.6).std() / (to_density(lo)[..., 1] - 0.3).std()
    check(abs(r - math.sqrt(1.65 / 0.35)) < 0.15, "grain grows with sqrt(density) (ratio %.2f)" % r)

    wild = [(v, v, v) for v in (-10.0, -0.5, 0.0, 0.5, 3.0, 1e4)] * 10
    o = run("fx_grain", wild, 60, 1, uiGrainAmount=3, uiShadowGrain=2, uiGauge=S8)
    check(np.all(np.isfinite(o)), "finite for extreme inputs")


def test_chain():
    section("chain: Core (negative) -> Grain -> Core (print)")
    core = os.path.join(HERE, "mcf_harness")
    if not os.path.exists(core):
        check(False, "tests/mcf_harness missing - run tests/test_film_core.py first")
        return

    def run_core(px, **ui):
        payload = "".join("%s %s %s\n" % tuple(float(c).hex() for c in p) for p in px)
        r = subprocess.run([core] + ["%s=%s" % kv for kv in ui.items()], input=payload, capture_output=True, text=True)
        return [tuple(float.fromhex(x) for x in l.split()) for l in r.stdout.splitlines()]
    W, H = 512, 64
    grey = [(f32(m.di_encode(m.MIDGRAY)),) * 3] * (W * H)
    neg = run_core(grey, uiOutput=[e for e, _ in m.OUTPUTS].index("OUT_CINEON"))
    g = run("fx_grain", neg, W, H, uiGauge=S16, uiNegative=1)
    pr = np.array(run_core([tuple(p) for p in g.reshape(-1, 3)], uiInput=[e for e, _ in m.INPUTS].index("IN_CINEON")))
    ref = run_core(grey[:1])[0]
    check(abs(pr[:, 1].mean() - ref[1]) < 0.01, "grain does not shift the printed grey (mean %.4f vs %.4f)" %
          (pr[:, 1].mean(), ref[1]))
    check(0.005 < pr[:, 1].std() < 0.1, "grain is visible in the print (RMS %.4f code values)" % pr[:, 1].std())


